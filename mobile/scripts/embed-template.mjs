// Embeds the team workbook (../Climbing_Team_Tiered_Practice_System.xlsx) into the app as
// src/data/template-xlsx.ts, so "Create a new team Sheet" can upload it to Google Drive,
// which converts it to a Google Sheet with every formula, dropdown, color rule and named
// range intact — the same way the original Sheet was made. Re-run (npm run template) after
// changing the workbook.
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../Climbing_Team_Tiered_Practice_System.xlsx", import.meta.url);
const out = new URL("../src/data/template-xlsx.ts", import.meta.url);
const b64 = readFileSync(src).toString("base64");
writeFileSync(out, `// Generated by scripts/embed-template.mjs from Climbing_Team_Tiered_Practice_System.xlsx — do not edit.
export const TEMPLATE_XLSX_BASE64 =
  ${JSON.stringify(b64)};
`);
console.log(`Embedded the workbook (${Math.round(b64.length / 1024)} KB as base64).`);
